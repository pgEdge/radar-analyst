# ---------------------------------------------------------------
# alter_system_drift
# ---------------------------------------------------------------

_AUTO_CONF_HEADER_ONLY = (
    "# Do not edit this file manually!\n"
    "# It will be overwritten by the ALTER SYSTEM command.\n"
)

_AUTO_CONF_WITH_SETTINGS = (
    "# Do not edit this file manually!\n"
    "# It will be overwritten by the ALTER SYSTEM command.\n"
    "work_mem = '64MB'\n"
    "max_connections = '200'\n"
)


def test_alter_system_fires_when_settings_present() -> None:
    parsed = {
        "pg.conf.postgresql_auto": _AUTO_CONF_WITH_SETTINGS
    }
    out = alter_system_drift(parsed)
    assert len(out) == 1
    assert out[0].severity == "warning"
    assert out[0].rule_id == "pg.conf.alter_system_drift"


def test_alter_system_silent_on_header_only() -> None:
    parsed = {"pg.conf.postgresql_auto": _AUTO_CONF_HEADER_ONLY}
    assert alter_system_drift(parsed) == []


def test_alter_system_silent_when_no_data() -> None:
    assert alter_system_drift({}) == []


def test_alter_system_silent_on_empty_string() -> None:
    parsed = {"pg.conf.postgresql_auto": ""}
    assert alter_system_drift(parsed) == []
