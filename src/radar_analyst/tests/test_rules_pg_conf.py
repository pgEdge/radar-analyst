"""Tests for rules/pg_conf.py: HBA trust/md5/error,
ALTER SYSTEM drift.
"""

from __future__ import annotations

from radar_analyst.parse.pg_conf import HbaRule
from radar_analyst.rules.pg_conf import (
    alter_system_drift,
    hba_config_error,
    md5_method_present,
    trust_method_present,
)


def _rule(
    type: str = "host",
    auth_method: str = "scram-sha-256",
    address: str = "0.0.0.0",
    rule_number: int = 1,
    error: str = "",
) -> HbaRule:
    return HbaRule(
        rule_number=rule_number,
        type=type,
        database="{all}",
        user_name="{all}",
        address=address,
        auth_method=auth_method,
        options="",
        error=error,
    )


# ---------------------------------------------------------------
# trust_method_present
# ---------------------------------------------------------------

def test_trust_fires_on_host_trust() -> None:
    parsed = {
        "pg.hba_file_rules": [_rule(type="host", auth_method="trust")]
    }
    out = trust_method_present(parsed)
    assert len(out) == 1
    assert out[0].severity == "critical"
    assert out[0].rule_id == "pg.conf.hba_trust"


def test_trust_fires_on_hostssl_trust() -> None:
    parsed = {
        "pg.hba_file_rules": [
            _rule(type="hostssl", auth_method="trust")
        ]
    }
    out = trust_method_present(parsed)
    assert len(out) == 1


def test_trust_silent_on_local_trust() -> None:
    # Unix-socket trust for postgres is common and acceptable.
    parsed = {
        "pg.hba_file_rules": [_rule(type="local", auth_method="trust")]
    }
    assert trust_method_present(parsed) == []


def test_trust_silent_on_host_scram() -> None:
    parsed = {
        "pg.hba_file_rules": [
            _rule(type="host", auth_method="scram-sha-256")
        ]
    }
    assert trust_method_present(parsed) == []


def test_trust_silent_when_no_data() -> None:
    assert trust_method_present({}) == []


def test_trust_silent_on_empty_list() -> None:
    assert trust_method_present({"pg.hba_file_rules": []}) == []


